function catalogIntro(site) {
  const country = (site.country || '').replace(/,/g, '、')
  const year = site.year ? `${site.year} 年` : ''
  const cat = site.category ? `${site.category}遗产` : '世界遗产'
  return `${site.name}位于${country}${year ? `，${year}列入《世界遗产名录》` : '，已列入《世界遗产名录》'}，属${cat}。平台目前收录了它的官方编号、坐标与名录档案。`
}

export function siteIntro(site) {
  if (!site) return ''
  return INTROS[site.id] || catalogIntro(site)
}
